/**
 * 拼接最终输出文本：象意 + 用神/世应判断 + 简短建议结尾。
 * 用神的解释靠 ctx，加在象意后面一行。
 */
export function getInterpretation(ctx: InterpretationContext): string {
  const base = DICT[ctx.hexName];
  const fallback = `${ctx.hexName}：当下处在${ctx.palace}宫的${ctx.palaceElement}气场中。`;
  const xiang = base ?? fallback;

  const yongLine = (() => {
    if (!ctx.yongShen) return '';
    const desc: Record<string, string> = {
      '父母': '用神为父母，主庇佑、规范、长辈或文书事',
      '官鬼': '用神为官鬼，主功名、压力、克身之事',
      '兄弟': '用神为兄弟，主同辈、争夺、阻力之事',
      '子孙': '用神为子孙，主解忧、福德、技艺与下属',
      '妻财': '用神为妻财，主财利、所求之物、关系中的"得到"',
    };
    return desc[ctx.yongShen] ?? `用神为${ctx.yongShen}`;
  })();

  const shiYing = ctx.shi && ctx.ying
    ? `世在${toCnNum(ctx.shi)}爻、应在${toCnNum(ctx.ying)}爻——${ctx.shi === ctx.ying ? '同位呼应' : '彼此牵动'}。`
    : '';

  const changed = ctx.changedName && ctx.hasMoving
    ? `动爻牵出"${ctx.changedName}"——这是事态翻面之后你将面对的下一程。`
    : ctx.hasMoving ? '动爻已现，事态正在转折。' : '六爻俱静，事态稳定，不轻易翻面。';

  const ending = '断卦本不是预言，是把脑中那张混沌的图先映出一个轮廓——剩下的，你自己看着办。';

  return [xiang, [yongLine, shiYing].filter(Boolean).join(''), changed, ending].filter(Boolean).join('\n\n');
}

function toCnNum(n: number): string {
  return ['初', '二', '三', '四', '五', '上'][n - 1] ?? String(n);
}
